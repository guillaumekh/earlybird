#!/usr/bin/env python3
"""Generate the application into build/, ready to copy to the Pico.

All settings are read from environment variables, listed in
local.env.example. How they get into the environment is up to the caller,
for example a secrets manager wrapping the command:

    op run --env-file=local.env -- make build

OTLP_BEARER_TOKEN is asked for if it is not set.
"""
import getpass
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
BUILD = ROOT / "build"
NOT_DEPLOYED = {"diag.py"}


def setting(name, prompt=False):
    value = os.environ.get(name, "")
    if not value and prompt and sys.stdin.isatty():
        value = getpass.getpass(f"{name}: ")
    value = value.strip()
    if not value:
        sys.exit(f"error: {name} is not set in the environment; see local.env.example")
    if value.startswith("op://"):
        sys.exit(f"error: {name} is an unresolved 1Password reference; run the build through 'op run'")
    return value


def main():
    settings = {
        "WIFI_SSID": setting("WIFI_SSID"),
        "WIFI_PASSWORD": setting("WIFI_PASSWORD"),
        "OTLP_URL": setting("OTLP_URL"),
        "OTLP_BEARER_TOKEN": setting("OTLP_BEARER_TOKEN", prompt=True),
    }
    if any(c in settings["OTLP_BEARER_TOKEN"] for c in " \r\n\t"):
        sys.exit("error: OTLP_BEARER_TOKEN contains whitespace")
    if not settings["OTLP_URL"].startswith("http://"):
        sys.exit("error: OTLP_URL must start with http://")

    if BUILD.exists():
        shutil.rmtree(BUILD)
    BUILD.mkdir()
    names = []
    for path in sorted(SRC.glob("*.py")):
        if path.name not in NOT_DEPLOYED:
            shutil.copy(path, BUILD / path.name)
            names.append(path.name)

    lines = ["# Generated by tools/build.py. Do not commit."]
    lines += [f"{key} = {value!r}" for key, value in settings.items()]
    target = BUILD / "device_secrets.py"
    target.touch(mode=0o600)
    target.write_text("\n".join(lines) + "\n")
    names.append(target.name)

    print(f"built {len(names)} files in {BUILD.relative_to(ROOT)}/: {', '.join(names)}")


if __name__ == "__main__":
    main()
